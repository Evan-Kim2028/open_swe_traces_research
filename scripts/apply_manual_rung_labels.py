def main() -> None:
    samples = json.loads(SAMPLE_JSON.read_text())
    rows = []
    missing = []
    for s in samples:
        iid = s["instance_id"]
        if iid not in MANUAL:
            missing.append(iid)
            continue
        rows.append(
            {
                "instance_id": iid,
                "rung_heuristic": s["rung_heuristic"],
                "rung_manual": MANUAL[iid],
            }
        )
    if missing:
        raise SystemExit(f"Missing manual labels for {len(missing)} instances: {missing[:5]}")
    VALIDATION_JSON.parent.mkdir(parents=True, exist_ok=True)
    VALIDATION_JSON.write_text(json.dumps(rows, indent=2))
    import pandas as pd

    manual = pd.read_json(VALIDATION_JSON)
    stats = agreement_stats(manual)
    print(f"Wrote {len(rows)} labels → {VALIDATION_JSON.relative_to(ROOT)}")
    print(
        f"Exact: {100 * stats['exact']:.1f}%  within±1: {100 * stats['within_1']:.1f}%  "
        f"ρ={stats['spearman']:.3f}"
    )
    print(confusion_matrix(manual).to_string())


if __name__ == "__main__":
    main()
